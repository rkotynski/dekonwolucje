"""Small two-language translation layer used by the GUI.

English source strings are the stable message identifiers.  This intentionally
keeps the implementation compact because the application supports exactly two
languages: English and Polish.  Code comments, docstrings, configuration keys
and algorithm identifiers remain in English.
"""
from __future__ import annotations

import re
import weakref
from typing import Callable, Dict, Iterable, List

SUPPORTED_LANGUAGES = ("en", "pl")
_LANGUAGE = "en"
_RETRANSLATORS: List[weakref.ReferenceType] = []


def normalize_language(language: str) -> str:
    value = str(language or "en").strip().lower()
    return "pl" if value.startswith("pl") else "en"


def get_language() -> str:
    return _LANGUAGE


def set_language(language: str) -> str:
    global _LANGUAGE
    _LANGUAGE = normalize_language(language)
    return _LANGUAGE


def register_retranslator(callback: Callable[[], None]) -> None:
    try:
        ref = weakref.WeakMethod(callback)  # bound method
    except TypeError:
        ref = weakref.ref(callback)
    _RETRANSLATORS.append(ref)


def retranslate_all() -> None:
    alive: List[weakref.ReferenceType] = []
    for ref in _RETRANSLATORS:
        callback = ref()
        if callback is None:
            continue
        alive.append(ref)
        try:
            callback()
        except RuntimeError:
            # The underlying Qt object may already have been deleted.
            continue
    _RETRANSLATORS[:] = alive


