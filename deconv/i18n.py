_TEMPLATE_REGEX = [
    (
        re.compile("^" + re.escape(source).replace(r"\{\}", "(.*?)") + "$", re.DOTALL),
        target,
    )
    for source, target in _TEMPLATE_PL.items()
]


def _format_template(target: str, values: Iterable[str]) -> str:
    parts = target.split("{}")
    values = list(values)
    output = [parts[0]]
    for index, value in enumerate(values):
        output.append(translate(value) if value else value)
        if index + 1 < len(parts):
            output.append(parts[index + 1])
    if len(parts) > len(values) + 1:
        output.extend(parts[len(values) + 1:])
    return "".join(output)

