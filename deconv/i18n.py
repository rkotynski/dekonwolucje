def translate(text: object) -> str:
    source = "" if text is None else str(text)
    if _LANGUAGE != "pl" or not source:
        return source
    exact = _EXACT_PL.get(source)
    if exact is not None:
        return exact
    # A whitespace-normalized lookup handles adjacent Python string literals.
    normalized = " ".join(source.split())
    exact = _EXACT_PL.get(normalized)
    if exact is not None:
        return exact
    for pattern, target in _TEMPLATE_REGEX:
        match = pattern.match(source)
        if match is not None:
            return _format_template(target, match.groups())
    result = source
    for english, polish in sorted(_PHRASE_PL, key=lambda item: len(item[0]), reverse=True):
        # Match complete words/phrases only. This prevents replacements such as
        # crop -> wycinek from corrupting the English word "cropped".
        pattern = r"(?<!\w)" + re.escape(english) + r"(?!\w)"
        result = re.sub(pattern, polish, result)
    return result


def language_display_name(language: str) -> str:
    language = normalize_language(language)
    if language == "pl":
        return "Polski"
    return "English"
